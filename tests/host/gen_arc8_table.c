/* Regenerate with gcc -O1 -ffp-contract=off -Ifirmware/src tests/host/gen_arc8_table.c. */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include "dsp/fastmath.h"
static float turns(float y, float x)
{
    float ax = fm_fabsf(x), ay = fm_fabsf(y), a = ax < ay ? ax / (ay + 1e-9f) : ay / (ax + 1e-9f), s = a * a, r;
    r = ((-0.0464964749f * s + 0.15931422f) * s - 0.327622764f) * s * a + a;   /* atan on [0, 1] */
    if (ay > ax)
        r = 1.57079637f - r;
    if (x < 0.0f)
        r = FM_PI - r;
    if (y < 0.0f)
        r = FM_TWO_PI - r;
    return r * (1.0f / FM_TWO_PI);
}

int main(void)
{
    puts("/* SPDX-License-Identifier: GPL-3.0-only */");
    puts("/* Generated by tests/host/gen_arc8_table.c with the original float arithmetic. */");
    puts("static const struct { int8_t x, y; uint8_t coverage; uint32_t turns_bits; } arc8_geometry[] = {");
    for (int y = -9; y <= 9; ++y) for (int x = -9; x <= 9; ++x) {
        float dx = (float)x + 0.5f - 0.5f, dy = (float)y + 0.5f - 0.5f;
        float d = fm_sqrtf(dx * dx + dy * dy), t;
        float a = fm_clampf(8.0f + 0.5f - d, 0.0f, 1.0f) * fm_clampf(d - (8.0f - 3.4f) + 0.5f, 0.0f, 1.0f);
        if (a <= 0.0f) continue;
        t = turns(dy, dx) - 0.375f;
        if (t < 0.0f) t += 1.0f;
        t /= 0.75f;
        if (t > 1.0f) continue;
        uint32_t bits; memcpy(&bits, &t, sizeof bits);
        printf("    {%d, %d, %u, 0x%08xu},\n", x, y, (unsigned)(a * 16.0f + 0.5f), (unsigned)bits);
    }
    puts("};");
    return 0;
}
