"""Validate the design model and export its actual canvas pixels; no firmware tests."""
import base64
import hashlib
import json
from pathlib import Path
from playwright.sync_api import sync_playwright
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent
QA = ROOT / 'qa'
QA.mkdir(exist_ok=True)
(QA/'native').mkdir(exist_ok=True)
(QA/'enlarged').mkdir(exist_ok=True)
results = []
frames = []

with sync_playwright() as pw:
    browser = pw.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1400,'height':1100}, device_scale_factor=1)
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto('http://127.0.0.1:8764/index.html')
    def run(js):
        return page.evaluate(js)
    def check(name, js):
        ok = run(js)
        results.append({'check':name,'passed':bool(ok)})
        assert ok, name
    def reset():
        run('study.reset()')
    def go(g):
        reset()
        run(f"study.dispatch('GLOBE'); for(let i=0;i<{g};i++)study.dispatch('SELECT+');study.arrowDown(1);study.arrowUp()")
    def shot(name):
        run('study.render()')
        bounds = run('study.bounds')
        assert all(b['x'] >= 0 and b['x']+b['w'] <= 240 and b['y']+b['h'] <= 240 for b in bounds), name
        for canvas,folder in [('lcd','native'),('large','enlarged')]:
            data = page.locator('#'+canvas).evaluate("c=>c.toDataURL('image/png').split(',')[1]")
            (QA/folder/(name+'.png')).write_bytes(base64.b64decode(data))
        frames.append({'id':name,'view':run('study.state.view'),'section':run('study.state.g'),'row':run('study.state.pos'),'clip':run('study.state.clip'),'dev':run('study.state.dev'),'bounds':bounds,'evidence':'SIMULATED_DESIGN_RENDER'})

    check('six categories / 36 inventoried source refs', 'study.groups.length===6 && study.allRows.flat().length===36')
    reset()
    run("study.dispatch('GLOBE');study.dispatch('SELECT-')")
    check('first category does not wrap','study.state.cat===0')
    run("for(let i=0;i<20;i++)study.dispatch('SELECT+')")
    check('last category does not wrap','study.state.cat===5')
    run('study.arrowDown(1);study.advance(2000)')
    check('held category entry does not run action', 'study.state.g===5 && !study.state.action && Object.values(study.state.counts).every(v=>v===0)')
    run('study.arrowUp()')
    go(0)
    run("study.dispatch('PATCH');study.arrowDown(1);study.advance(400);study.advance(80);study.advance(80)")
    check('held entry never edits first CLOCK SOURCE','study.state.values.R_CLKSRC===0')
    shot('held-entry-consumed')
    run('study.arrowUp();study.arrowDown(1)')
    check('fresh > edits one value','study.state.values.R_CLKSRC===1')
    run('study.advance(399)')
    check('no repeat before 400ms','study.state.values.R_CLKSRC===1')
    run('study.advance(1)')
    check('repeat at 400ms','study.state.values.R_CLKSRC===2')
    run('study.advance(80);study.advance(80)')
    check('held repeat saturates at upper bound','study.state.values.R_CLKSRC===2')
    shot('clock-upper-bound')
    run("study.arrowUp();study.dispatch('ALGORITHM-')")
    check('K3 decrements EXTERNAL to INTERNAL','study.state.values.R_CLKSRC===1')
    run('study.arrowDown(-1);study.advance(1000)')
    check('< backs and consumes repeat without value decrement','study.state.g===-1 && study.state.cat===0 && study.state.values.R_CLKSRC===1')
    run('study.arrowUp();study.arrowDown(1);study.arrowUp()')
    check('re-entry retains row','study.state.g===0 && study.state.pos===0')
    run("study.dispatch('ALGORITHM-');study.dispatch('ALGORITHM-')")
    check('lower value does not wrap','study.state.values.R_CLKSRC===0')
    run("for(let i=0;i<20;i++)study.dispatch('SELECT+')")
    check('last MIDI row, scroll and boundary','study.state.pos===8 && study.state.top===3')
    shot('midi-last-boundary')
    run("study.dispatch('PATCH');study.arrowDown(1);study.arrowUp()")
    check('PATCH restores category and re-entry preserves scroll','study.state.pos===8 && study.state.top===3')
    for g in range(6):
        go(g)
        check(f'category {g} count', f'study.rows().length==={[9,5,10,3,5,3][g]}')
        for i in range(run('study.rows().length')):
            run(f'study.state.pos={i};study.state.top=Math.max(0,{i}-5);study.render()')
            shot(f'category-{g}-row-{i:02}')
        run("study.dispatch('PATCH')")
        check(f'category {g} focus restored', f'study.state.g===-1 && study.state.cat==={g}')
        shot(f'category-focus-{g}')
    go(4)
    for pos in [0,3,4]:
        run(f'study.state.pos={pos};study.render();study.dispatch("ALGORITHM+");study.dispatch("ALGORITHM-");study.arrowDown(1);study.advance(1000);study.arrowUp()')
        check(f'action row {pos} inert under encoder and held >','Object.values(study.state.counts).every(v=>v===0) && !study.state.modal')
    for pos in [1,3,4]:
        run(f'study.state.pos={pos};study.dispatch("SCALE")')
        check(f'question {pos} opens without commit','!!study.state.modal && Object.values(study.state.counts).every(v=>v===0)')
        shot(f'question-{pos}')
        run('study.dispatch("GLOBE")')
        check('GLOBE ignored by question','!!study.state.modal')
        run('study.dispatch("PATCH")')
        check(f'question {pos} cancellation returns exact row',f'!study.state.modal && study.state.g===4 && study.state.pos==={pos}')
    run('study.state.pos=0;study.dispatch("SCALE")')
    check('deliberate SAVE activation exactly once, simulated only','study.state.counts.save===1 && study.state.counts.reset===0')
    check('SAVE is labelled as request, without clearing dirty','study.state.dirty && study.bounds.some(x=>x.shown==="SCALE requests save") && study.state.notice.includes("defers writing while RUN")')
    run('study.state.pos=4;study.dispatch("SCALE");study.dispatch("SCALE")')
    check('deliberate RESET confirm exactly once, simulated only','study.state.counts.reset===1')
    go(4)
    run('study.state.pos=1;study.render()')
    page.locator('#dirty').uncheck()
    check('clean LOAD has direct request cue','!study.state.dirty && study.bounds.some(x=>x.shown==="SCALE requests load")')
    shot('clean-load-direct')
    page.get_by_role('button',name='SCALE',exact=True).click()
    check('clean LOAD requests once without a question','!study.state.modal && study.state.counts.load===1 && !study.state.dirty')
    page.locator('#dirty').check()
    page.get_by_role('button',name='SCALE',exact=True).click()
    check('dirty LOAD asks without another request','!!study.state.modal && study.state.counts.load===1')
    page.get_by_role('button',name='PATCH',exact=True).click()
    check('dirty LOAD cancel restores exact row','!study.state.modal && study.state.pos===1 && study.state.g===4')
    run('study.state.pos=4;study.dispatch("SCALE")')
    check('modal fully masks underlying focus strip','(()=>{const p=document.getElementById("lcd").getContext("2d").getImageData(5,154,1,1).data;return p[0]===11&&p[1]===23&&p[2]===21})()')
    shot('modal-full-focus-mask')
    go(4)
    run('study.state.clip=true;study.dispatch("SCALE");study.arrowDown(1);study.advance(2000);study.arrowUp()')
    check('clip SCALE and arrows cannot run SAVE','study.state.counts.save===0 && !study.state.modal')
    shot('clip-save-masked')
    run('study.state.pos=2;study.dispatch("ALGORITHM-")')
    check('K3 works in clip menu','study.state.values.R_AUTOSAVE===0')
    go(5)
    run('study.state.dev=true;study.render()')
    check('developer nonclip pad colours included','study.rows().length===4')
    run('study.state.pos=3;study.render()')
    shot('developer-pad-colours')
    run('study.state.clip=true;study.state.pos=2;study.render()')
    check('clip hides PAD COLOURS','study.rows().length===3')
    shot('clip-system-mask')
    reset()
    run('study.state.smk=false;study.dispatch("GLOBE")')
    check('non-SMK Bluetooth category absent','study.state.smk===false && document.getElementById("detail").textContent.includes("MIDI")')
    run('study.arrowDown(1);study.arrowUp()')
    check('non-SMK clip channel absent','study.rows().length===8')
    go(1)
    run('study.state.pos=3;study.render()')
    check('STATUS retains READY on native LCD and read-only footer','study.bounds.some(x=>x.shown==="READY") && study.bounds.some(x=>x.shown==="Read only")')
    go(5)
    run('study.state.pos=2;study.render()')
    check('BATTERY retains USB POWER on native LCD','study.bounds.some(x=>x.shown==="USB POWER")')
    go(1)
    run('study.state.pos=4;study.render();study.dispatch("ALGORITHM+");study.arrowDown(1);study.advance(1000);study.arrowUp()')
    check('long NAME read-only and clipped to value region','study.state.values.R_BTNAME===0 && study.bounds.some(x=>x.text.includes("SMC-Mixer"))')
    shot('long-peer-clipped')
    check('full two-peer identity visible within native detail strip','study.bounds.some(x=>x.shown==="1: SMC-Mixer-Stage-Left") && study.bounds.some(x=>x.shown==="2: Keys-Right")')
    go(2)
    run('study.state.pos=2;study.state.values.R_FINETUNE=0;study.dispatch("ALGORITHM-")')
    check('Tune lower bound 0 raw / -40.0 Hz','study.state.values.R_FINETUNE===0')
    shot('tune-lower-bound')
    run('study.state.values.R_FINETUNE=127;study.dispatch("ALGORITHM+")')
    check('Tune upper bound 127 raw / +39.3 Hz','study.state.values.R_FINETUNE===127')
    shot('tune-upper-bound')
    reset()
    run('study.state.held=true;study.dispatch("GLOBE")')
    check('navigation preserves transport but exposes retired local key','study.state.playing && !study.state.held && study.state.retired')
    shot('held-key-retired')
    run('study.dispatch("GLOBE")')
    check('GLOBE restores original view','study.state.view==="part" && study.state.playing')
    shot('exit-original-view')
    go(4)
    run('study.state.pos=4;study.dispatch("SCALE");study.dispatch("SEQ PLAY")')
    check('PLAY cancels question and stops previously running transport','!study.state.modal && !study.state.playing && study.state.counts.reset===0')
    shot('play-cancels-and-stops')
    page.get_by_role('button',name='Restart illustrative session',exact=True).click()
    page.get_by_role('button',name='GLOBE',exact=True).click()
    page.get_by_role('button',name='K2 +',exact=True).click()
    page.get_by_role('button',name='>',exact=True).click()
    check('actual pointer controls navigate to Bluetooth','study.state.g===1')
    page.get_by_role('button',name='PATCH',exact=True).click()
    check('actual PATCH click restores focus','study.state.g===-1 && study.state.cat===1')
    page.get_by_role('button',name='Held entry',exact=True).click()
    page.get_by_role('button',name='>',exact=True).focus()
    page.keyboard.down('Enter')
    page.wait_for_timeout(900)
    page.keyboard.up('Enter')
    check('keyboard held entry consumed without edit','study.state.g===0 && study.state.values.R_CLKSRC===0')
    page.keyboard.down('Enter')
    page.wait_for_timeout(900)
    page.keyboard.up('Enter')
    check('keyboard fresh hold uses repeat timer','study.state.values.R_CLKSRC===2 && study.state.ms>=1600')
    shot('keyboard-repeat-upper-bound')
    check('edited EXTERNAL source shows waiting fixture clock','study.bounds.some(x=>x.shown==="WAIT EXT")')
    run('study.scene("USB AUDIO")')
    page.screenshot(path=str(QA/'walkthrough-browser.png'),full_page=True)
    receipt={'evidence':'SIMULATED_DESIGN_MODEL_AND_CANVAS_RENDER','browser':browser.version,'command':'python3 verify.py','passed':sum(x['passed'] for x in results),'failed':sum(not x['passed'] for x in results),'page_errors':errors,'results':results,'frames':len(frames),'firmware_tests_run':False,'audio_observed':False}
    assert not errors, errors
    (QA/'interaction-results.json').write_text(json.dumps(receipt,indent=2)+'\n')
    (QA/'frame-manifest.json').write_text(json.dumps(frames,indent=2)+'\n')
    (ROOT/'inventory.json').write_text(json.dumps(run('study.allRows'),indent=2)+'\n')
    browser.close()

names=[f['id'] for f in frames]
sheet=Image.new('RGB',(5*264,((len(names)+4)//5)*280),'#101719')
draw=ImageDraw.Draw(sheet)
for i,name in enumerate(names):
    x=(i%5)*264+12;y=(i//5)*280+6
    sheet.paste(Image.open(QA/'native'/(name+'.png')),(x,y))
    draw.text((x,y+246),name,fill='#e3f2e7')
sheet.save(QA/'contact-sheet.png')
print(json.dumps(receipt|{'results':'see receipt'},indent=2))
