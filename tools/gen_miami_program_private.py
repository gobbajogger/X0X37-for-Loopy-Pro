"""Generate a shared-context original program and independent saved-state fixture.

Consumes functional reference reports only. No original binary/resources are
copied, executed or redistributed. Private output, no activation/publication.
"""
import argparse, hashlib, json, pathlib, struct

PINS = {
    'Miami-original-macro-native-mapping-20261028.json': '2d800924fbee4649e9d5c91f1943ec9b020c05697db9338513feb963cf671e65',
    'miami-native-saved-normalized-array-check.json': 'c6ea0896434fefdd62866ee0de350b736ed47436416a7332b8bb03aebec9fff7',
    'Miami-original-preset-findings-20261028.json': '955aa3e12f7d0a60b0890113fbbd27a3ae90f9dc001c049d874cb5abdc2e50af',
}

def load(root, name):
    b = (root / name).read_bytes()
    if hashlib.sha256(b).hexdigest() != PINS[name]:
        raise ValueError('reference pin mismatch: ' + name)
    return json.loads(b)

def literal(x):
    f = struct.unpack('<f', struct.pack('<f', x))[0]
    return f.hex() + 'f'

def generate(root, header, fixture):
    mapping = load(root, next(iter(PINS)))
    states = load(root, 'miami-native-saved-normalized-array-check.json')['state_arrays']
    records = load(root, 'Miami-original-preset-findings-20261028.json')['original_resource_bank']['records']
    by_name = {r['name']: r for r in records}
    assert len(states) == len(by_name) == 30
    ids = [t['target_id'] for c in mapping['controls'] for t in c['targets']]
    assert len(ids) == len(set(ids)) == 24
    shared = states[0]['candidate_normalized109']
    assert len(shared) == 109
    for s in states:
        assert all(s['candidate_normalized109'][i] == shared[i] for i in range(109) if i not in ids)
        assert len(by_name[s['name']]['parameters']) == 18
    counts = {1:5,9:5,5:5,43:5,49:5,2:49,10:49,47:10,48:16,24:1281,80:2001,81:2001,108:128,110:128,111:128}
    rows, lookup, starts = [], [], [0]
    for c in mapping['controls']:
        assert c['macro_id'] == len(starts)-1
        for t in c['targets']:
            values = t['numeric_payload']; typ = t['type_code']; i = t['target_id']
            at = len(lookup)
            if typ == 2:
                lookup.extend(values); a = b = 0
            else:
                assert typ in (0,3) and len(values) == 2
                a,b = values
            # Semitone carries an outer Q1201 step before the Q49 round trip.
            rows.append('{%d,%d,%d,%d,%d,%d,%s,%s}' % (i,typ,len(values),at,counts.get(i,1001),1201 if i in (2,10) else 0,literal(a),literal(b)))
        starts.append(len(rows))
    lines = [
        '/* PRIVATE functional program metadata. No active engine or publication. */',
        'typedef struct {uint16_t native_id;uint8_t type,length,lookup;uint16_t canonical_count,outer_count;float a,b;} original_miami_mapping;',
        'static const uint8_t original_miami_macro_start[19]={' + ','.join(map(str,starts)) + '};',
        'static const original_miami_mapping original_miami_mappings[24]={' + ',\n'.join(rows) + '};',
        'static const float original_miami_lookup[%d]={' % len(lookup) + ','.join(map(literal,lookup)) + '};',
        'static const float original_miami_base[109]={' + ','.join(map(literal,shared)) + '};',
        'static const char original_miami_factory_name[30][24]={' + ','.join(json.dumps(s['name']) for s in states) + '};',
        'static const float original_miami_factory_macro[30][18]={',
    ]
    for s in states:
        lines.append('{' + ','.join(map(literal,by_name[s['name']]['parameters'])) + '},')
    lines += ['};', '']
    # Golden saved vectors come directly from the independently recovered state
    # report. They are not generated by replaying this implementation's map.
    raw = bytearray()
    for s in states:
        raw += struct.pack('<109f', *s['candidate_normalized109'])
    header.write_text('\n'.join(lines))
    fixture.write_bytes(raw)
    print(json.dumps({'factories':30,'shared_fields':109-len([i for i in ids if i<109]),'targets':24,'fixture_sha256':hashlib.sha256(raw).hexdigest(),'fixture_bytes':len(raw)},sort_keys=True))

if __name__ == '__main__':
    p=argparse.ArgumentParser();p.add_argument('references',type=pathlib.Path);p.add_argument('header',type=pathlib.Path);p.add_argument('fixture',type=pathlib.Path);a=p.parse_args()
    generate(a.references,a.header,a.fixture)
