"""SMK-37 clip mode: make the pad LED table and the LCD table from one source.

Source: tools/apc40mk2_akai_protocol_v1.2.csv (Akai APC40 Mk2 Communications Protocol v1.2,
table "RGB LEDs"). The rules and their named constants are in tools/apc_colour_model.py.

Usage:
  tools/apc_pad_colors.py                      # table on stdout
  tools/apc_pad_colors.py --pad-h out.h        # APC40_PAD_DEFAULT[128]: pad LED start levels
  tools/apc_pad_colors.py --lcd-h out.h        # APC40_LCD565[128]: LCD colours
  tools/apc_pad_colors.py --report out.csv [--old-pad F] [--old-lcd F]   # old and new, hues
  tools/apc_pad_colors.py --html out.html [--old-pad F] [--old-lcd F]    # swatches
  --gamma G  --target apc|live  --no-balance   # try other values of the named constants
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import apc_colour_model as m  # noqa: E402

GEN = ("/* Generated by tools/apc_pad_colors.py {opt} from tools/apc40mk2_akai_protocol_v1.2.csv\n"
       " * (Akai APC40 Mk2 Communications Protocol v1.2, table \"RGB LEDs\"). Do not edit: run the tool.\n")


def pad_header(pad, gamma, balance, target):
    out = [GEN.format(opt="--pad-h") +
           f" * Pad LED level (0xRRGGBB) for each velocity: colour {target}, decode gamma {gamma},\n"
           f" * white gains {'on' if balance else 'off'} (WS2812B data sheet), brightest channel sends at least "
           f"{m.PAD_FLOOR_SENT}.\n"
           " * The start point of the pad calibration, not the live pad table (APC40_RGB in main_fm1.c). */",
           "static const uint32_t APC40_PAD_DEFAULT[128] = {"]
    for i in range(0, 128, 8):
        out.append("    " + ",".join(f"0x{m.join(*p):06X}" for p in pad[i:i + 8]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def lcd_header(lcd, target):
    out = [GEN.format(opt="--lcd-h") +
           f" * LCD clip colour (RGB565) for each velocity: colour {target}, no gamma. Brightest channel to\n"
           f" * {m.LCD_FLOOR}..255, then OKLCH lift to Y >= {m.LCD_YMIN} * (t/255)^2.2 at the hue at full brightness.\n"
           " * Index 0 is not drawn (empty cell). */",
           "static const uint16_t APC40_LCD565[128] = {"]
    for i in range(0, 128, 8):
        out.append("    " + ",".join(f"0x{c:04X}" for c in lcd[i:i + 8]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def read_table(path, name, digits):
    t = Path(path).read_text()
    mt = re.search(name + r"\[128\]\s*=\s*\{(.*?)\};", t, re.S)
    return [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{%d})\b" % digits, mt.group(1))]


def hx(t):
    return "#%02X%02X%02X" % tuple(int(round(min(255, max(0, x)))) for x in t)


def led_preview(levels):
    """Screen preview of the LED light: an sRGB colour with the same chromaticity."""
    X, Y, Z = m.led_xyz(levels)
    if Y <= 0:
        return (0, 0, 0)
    r = 3.2404542 * X - 1.5371385 * Y - 0.4985314 * Z
    g = -0.9692660 * X + 1.8760108 * Y + 0.0415560 * Z
    b = 0.0556434 * X - 0.2040259 * Y + 1.0572252 * Z
    lin = [max(0.0, c) for c in (r, g, b)]
    mx = max(lin)
    k = max(levels) / 255
    return tuple(m._enc(c / mx * k) for c in lin)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pad-h")
    ap.add_argument("--lcd-h")
    ap.add_argument("--report")
    ap.add_argument("--html")
    ap.add_argument("--old-pad")
    ap.add_argument("--old-lcd")
    ap.add_argument("--gamma", type=float, default=m.PAD_GAMMA)
    ap.add_argument("--target", choices=("apc", "live"), default=m.TARGET)
    ap.add_argument("--no-balance", action="store_true")
    a = ap.parse_args()
    bal = m.PAD_BALANCE and not a.no_balance
    src = m.load_source()
    pad = [m.pad_level(e, a.target, a.gamma, bal) for e in src]
    lcd = [m.lcd565(e, a.target) for e in src]
    if a.pad_h:
        Path(a.pad_h).write_text(pad_header(pad, a.gamma, bal, a.target))
    if a.lcd_h:
        Path(a.lcd_h).write_text(lcd_header(lcd, a.target))
    op = read_table(a.old_pad, "APC40_RGB", 6) if a.old_pad else None
    ol = read_table(a.old_lcd, "APC40_LCD565", 4) if a.old_lcd else None
    if a.report:
        with open(a.report, "w") as f:
            f.write("velocity,source,pad_old_send,pad_new_send,pad_led_hue_old,pad_led_hue_new,source_hue,"
                    "lcd_old,lcd_new,lcd_hue_old,lcd_hue_new\n")
            for e, p, c in zip(src, pad, lcd):
                v = e["v"]
                so = m.pad_send(m.split(op[v])) if op else None
                sn = m.pad_send(p)
                ho = m.led_hue(so)[0] if so else None
                hn = m.led_hue(sn)[0]
                f.write(f"{v},{e['apc']:06X},{'' if so is None else '/'.join(map(str, so))},{'/'.join(map(str, sn))},"
                        f"{'' if ho is None else format(ho, '.0f')},{'' if hn is None else format(hn, '.0f')},"
                        f"{m.full_hue(e['apc']) if e['apc'] else 0:.0f},"
                        f"{'' if ol is None else format(ol[v], '04X')},{c:04X},"
                        f"{'' if not ol or not ol[v] else format(m.lch(*m.of565(ol[v]))[2], '.0f')},"
                        f"{m.lch(*m.of565(c))[2] if c else 0:.0f}\n")
    if a.html:
        trs = []
        for e, p, c in zip(src, pad, lcd):
            v = e["v"]
            cells = [f"<td>{v}</td><td><span style='background:#{e['apc']:06X}'></span>#{e['apc']:06X}</td>"]
            if op:
                cells.append(f"<td><span style='background:{hx(led_preview(m.split(op[v])))}'></span>{op[v]:06X}</td>")
            cells.append(f"<td><span style='background:{hx(led_preview(p))}'></span>{m.join(*p):06X}</td>")
            if ol:
                cells.append(f"<td><span style='background:{hx(m.of565(ol[v]))}'></span>{ol[v]:04X}</td>")
            cells.append(f"<td><span style='background:{hx(m.of565(c))}'></span>{c:04X}</td>")
            trs.append("<tr>" + "".join(cells) + "</tr>")
        head = ("<th>vel</th><th>Akai colour</th>" + ("<th>pad old (LED model)</th>" if op else "") +
                "<th>pad new (LED model)</th>" + ("<th>LCD old</th>" if ol else "") + "<th>LCD new</th>")
        Path(a.html).write_text(
            "<!doctype html><meta charset=utf-8><title>APC40 colours</title><style>body{background:#111;"
            "color:#ddd;font:12px monospace}span{display:inline-block;width:40px;height:18px;margin-right:6px;"
            "vertical-align:middle}td{padding:2px 8px}</style><table><tr>" + head + "</tr>" + "".join(trs) +
            "</table>")
    if not (a.pad_h or a.lcd_h or a.report or a.html):
        print("vel  source  pad      lcd")
        for e, p, c in zip(src, pad, lcd):
            print(f"{e['v']:3d}  {e['apc']:06X}  {m.join(*p):06X}   {c:04X}")


if __name__ == "__main__":
    main()
