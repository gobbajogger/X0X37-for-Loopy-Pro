"""SMK-37 clip mode: make the pad LED table and the LCD table from one source.

Source: tools/apc40mk2_akai_protocol_v1.2.csv (Akai APC40 Mk2 Communications Protocol v1.2,
table "RGB LEDs"). The rules and their named constants are in tools/apc_colour_model.py.

Usage:
  tools/apc_pad_colors.py                      # table on stdout
  tools/apc_pad_colors.py --lcd-idle-h firmware/src/app/apc40_lcd_idle.h   # idle clip squares (CLP-05)
  tools/apc_pad_colors.py --names-h firmware/src/app/apc40_pad_names.h --names-csv names.csv   # CLP-79 names
  tools/apc_pad_colors.py --pad-h out.h        # APC40_PAD_DEFAULT[128][3]: pad LED start levels
  tools/apc_pad_colors.py --pad-h out.h --pad-override export.txt   # the entries marked ok replace the rule
  tools/apc_pad_colors.py --pad-h firmware/src/app/apc40_pad_owner.h --pad-override tools/padcal/pads-owner-20261017.txt \\
      --pad-name APC40_PAD_OWNER               # the live pad table (owner-calibrated, BEHAVIOR.md CLP-13)
  tools/apc_pad_colors.py --lcd-h out.h        # APC40_LCD565[128]: LCD colours
  tools/apc_pad_colors.py --gamma-h out.h      # PAD_GAMMA_LUT, PAD_GAIN_Q8, PAD_FLOOR_LEVEL (firmware)
  tools/apc_pad_colors.py --report out.csv [--old-pad F] [--old-lcd F]   # old and new, hues
  tools/apc_pad_colors.py --html out.html [--old-pad F] [--old-lcd F]    # swatches
  --gamma G  --target apc|live  --no-balance   # try other values of the named constants
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import apc_colour_model as m  # noqa: E402

GEN = ("/* Generated by tools/apc_pad_colors.py {opt} from tools/apc40mk2_akai_protocol_v1.2.csv\n"
       " * (Akai APC40 Mk2 Communications Protocol v1.2, table \"RGB LEDs\"). Do not edit: run the tool.\n")


def pad_header(pad, gamma, balance, target, override=None, name="APC40_PAD_DEFAULT", ov_path=None):
    ov = f" --pad-override ({len(override)} entries)" if override else ""
    head = (GEN.format(opt="--pad-h" + ov) +
            f" * Pad LED level (R, G, B) for each velocity: colour {target}, decode gamma {gamma},\n"
            f" * white gains {'on' if balance else 'off'} (WS2812B data sheet), trim {m.PAD_GAIN_TRIM},\n"
            f" * brightest channel sends at least {m.PAD_FLOOR_SENT}.\n")
    if override and name != "APC40_PAD_DEFAULT":
        sha = hashlib.sha256(Path(ov_path).read_bytes()).hexdigest() if ov_path else "?"
        head += (" * The owner-calibrated pad table: the pad calibration start values plus the entries marked ok\n"
                 f" * in the owner export {Path(ov_path).name if ov_path else '?'} (sha256 {sha[:16]}).\n"
                 " * The live pad table of clip mode (main_fm1.c smk_pads), in the dev and the release build.\n"
                 " * A lit clip pad sends level / 2, the same bytes as PAD COLOURS (BEHAVIOR.md CLP-13, CLP-79).\n"
                 " * Decimal: the build's register address check. */")
    else:
        head += (" * The pad calibration start values (the firmware makes them at run time from APC40_LCD565 and\n"
                 " * app/apc40_pad_gamma.h) plus the entries marked ok in an export. The firmware does not include\n"
                 " * this file. With an owner export, --pad-name APC40_PAD_OWNER writes the live pad table\n"
                 " * (app/apc40_pad_owner.h, BEHAVIOR.md CLP-13). Decimal: the build's register address check. */")
    out = [head, "#include <stdint.h>", f"static const uint8_t {name}[128][3] = {{"]
    for i in range(0, 128, 8):
        out.append("    " + ",".join("{%d,%d,%d}" % p for p in pad[i:i + 8]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def gamma_header(gamma, balance):
    lut, gain = m.pad_gamma_lut(gamma), m.pad_gain_q8(balance)
    return (GEN.format(opt="--gamma-h") +
            f" * The pad calibration start values (app/smk_padcal.h smk_padcal_default): decode gamma {gamma},\n"
            f" * white gains {'on' if balance else 'off'} (WS2812B data sheet) with trim {m.PAD_GAIN_TRIM} in Q8,\n"
            f" * floor {m.PAD_FLOOR_LEVEL} (the brightest channel sends at least {m.PAD_FLOOR_SENT}). */\n"
            "#include <stdint.h>\n"
            "static const uint8_t PAD_GAMMA_LUT[32] = {" + ",".join(map(str, lut)) + "};\n"
            "static const uint16_t PAD_GAIN_Q8[3] = {" + ",".join(map(str, gain)) + "};\n"
            f"#define PAD_FLOOR_LEVEL {m.PAD_FLOOR_LEVEL}u\n")


def lcd_header(lcd, target):
    out = [GEN.format(opt="--lcd-h") +
           f" * LCD clip colour (RGB565) for each velocity: colour {target} as plain RGB565 (no gamma, no lift).\n"
           " * Index 0 is not drawn (empty cell). */",
           "static const uint16_t APC40_LCD565[128] = {"]
    for i in range(0, 128, 8):
        out.append("    " + ",".join(f"0x{c:04X}" for c in lcd[i:i + 8]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def lcd_idle_header(src, target):
    idle = [m.lcd_idle565(src, v, target) for v in m.IDLE_SHADES]
    out = [GEN.format(opt="--lcd-idle-h") +
           f" * LCD colour (RGB565) of an idle clip square (BEHAVIOR.md CLP-05): for the darkest shade v of an Akai\n"
           f" * group (v = {m.IDLE_SHADES[0]}, {m.IDLE_SHADES[1]}, ... {m.IDLE_SHADES[-1]}, v % 4 == 3), half of the full shade v - 2\n"
           f" * (colour {target}, each 8-bit channel / 2, round half up), as RGB565. Entry i is v = {m.IDLE_SHADES[0]} + 4 i. */",
           f"static const uint16_t APC40_LCD_IDLE565[{len(idle)}] = {{",
           "    " + ",".join(f"0x{c:04X}" for c in idle) + ",", "};"]
    return "\n".join(out) + "\n"


def names_header(src):
    codes = [h << 3 | s for h, s in (m.entry_name(src, v) for v in range(128))]
    return (GEN.format(opt="--names-h") +
            " * The name of each pad calibration entry (BEHAVIOR.md CLP-79, dev build only): hue family and shade\n"
            " * from the Akai reference colour. Descriptive names made by the tool: the CSV has no names, and they\n"
            " * are not Loopy Pro colour names. Code = hue << 3 | shade. */\n"
            "#include <stdint.h>\n"
            "static const char *const PADCAL_HUE[" + str(len(m.NAME_HUES)) + "] = {" +
            ", ".join(f'"{n}"' for n in m.NAME_HUES) + "};\n"
            "static const char *const PADCAL_SHADE[" + str(len(m.NAME_SHADES)) + "] = {" +
            ", ".join(f'"{n}"' for n in m.NAME_SHADES) + "};\n"
            "static const uint8_t PADCAL_NAME[128] = {\n" +
            "".join("    " + ",".join(str(c) for c in codes[i:i + 16]) + ",\n" for i in range(0, 128, 16)) + "};\n")


def names_csv(src, owner):
    out = ["velocity,akai_hex,name,owner_r,owner_g,owner_b"]
    for v in range(128):
        o = owner[v] if owner else ("", "", "")
        out.append(f"{v},{src[v]['apc']:06X},{m.entry_name_text(src, v)},{o[0]},{o[1]},{o[2]}")
    return "\n".join(out) + "\n"


def read_table(path, name, digits):
    t = Path(path).read_text()
    mt = re.search(name + r"\[128\]\s*=\s*\{(.*?)\};", t, re.S)
    return [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{%d})\b" % digits, mt.group(1))]


def hx(t):
    return "#%02X%02X%02X" % tuple(int(round(min(255, max(0, x)))) for x in t)


def led_preview(levels):
    """Screen preview of the LED light: an sRGB colour with the same chromaticity."""
    X, Y, Z = m.led_xyz(levels)
    if Y <= 0:
        return (0, 0, 0)
    r = 3.2404542 * X - 1.5371385 * Y - 0.4985314 * Z
    g = -0.9692660 * X + 1.8760108 * Y + 0.0415560 * Z
    b = 0.0556434 * X - 0.2040259 * Y + 1.0572252 * Z
    lin = [max(0.0, c) for c in (r, g, b)]
    mx = max(lin)
    k = max(levels) / 255
    return tuple(m._enc(c / mx * k) for c in lin)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pad-h")
    ap.add_argument("--lcd-h")
    ap.add_argument("--gamma-h")
    ap.add_argument("--lcd-idle-h")
    ap.add_argument("--names-h")
    ap.add_argument("--names-csv")
    ap.add_argument("--report")
    ap.add_argument("--html")
    ap.add_argument("--pad-override")
    ap.add_argument("--pad-name", default="APC40_PAD_DEFAULT")
    ap.add_argument("--old-pad")
    ap.add_argument("--old-lcd")
    ap.add_argument("--gamma", type=float, default=m.PAD_GAMMA)
    ap.add_argument("--target", choices=("apc", "live"), default=m.TARGET)
    ap.add_argument("--no-balance", action="store_true")
    a = ap.parse_args()
    bal = m.PAD_BALANCE and not a.no_balance
    src = m.load_source()
    pad = [m.pad_level(e, a.target, a.gamma, bal) for e in src]
    lcd = [m.lcd565(e, a.target) for e in src]
    ov = m.read_override(a.pad_override) if a.pad_override else {}
    for v, p in ov.items():
        pad[v] = p
    if a.pad_h:
        Path(a.pad_h).write_text(pad_header(pad, a.gamma, bal, a.target, ov, a.pad_name, a.pad_override))
    if a.lcd_h:
        Path(a.lcd_h).write_text(lcd_header(lcd, a.target))
    if a.names_h:
        Path(a.names_h).write_text(names_header(src))
    if a.names_csv:
        oh = Path(__file__).resolve().parents[1] / "firmware/src/app/apc40_pad_owner.h"
        mt = re.search(r"APC40_PAD_OWNER\[128\]\[3\]\s*=\s*\{(.*?)\};", oh.read_text(), re.S)
        owner = [tuple(map(int, x)) for x in re.findall(r"\{(\d+),(\d+),(\d+)\}", mt.group(1))] if mt else None
        Path(a.names_csv).write_text(names_csv(src, owner))
    if a.lcd_idle_h:
        Path(a.lcd_idle_h).write_text(lcd_idle_header(src, a.target))
    if a.gamma_h:
        Path(a.gamma_h).write_text(gamma_header(a.gamma, bal))
    op = read_table(a.old_pad, "APC40_RGB", 6) if a.old_pad else None
    ol = read_table(a.old_lcd, "APC40_LCD565", 4) if a.old_lcd else None
    if a.report:
        with open(a.report, "w") as f:
            f.write("velocity,source,pad_old_send,pad_new_send,pad_led_hue_old,pad_led_hue_new,source_hue,"
                    "lcd_old,lcd_new,lcd_hue_old,lcd_hue_new\n")
            for e, p, c in zip(src, pad, lcd):
                v = e["v"]
                so = m.pad_send(m.split(op[v])) if op else None
                sn = m.pad_send(p)
                ho = m.led_hue(so)[0] if so else None
                hn = m.led_hue(sn)[0]
                f.write(f"{v},{e['apc']:06X},{'' if so is None else '/'.join(map(str, so))},{'/'.join(map(str, sn))},"
                        f"{'' if ho is None else format(ho, '.0f')},{'' if hn is None else format(hn, '.0f')},"
                        f"{m.full_hue(e['apc']) if e['apc'] else 0:.0f},"
                        f"{'' if ol is None else format(ol[v], '04X')},{c:04X},"
                        f"{'' if not ol or not ol[v] else format(m.lch(*m.of565(ol[v]))[2], '.0f')},"
                        f"{m.lch(*m.of565(c))[2] if c else 0:.0f}\n")
    if a.html:
        trs = []
        for e, p, c in zip(src, pad, lcd):
            v = e["v"]
            cells = [f"<td>{v}</td><td><span style='background:#{e['apc']:06X}'></span>#{e['apc']:06X}</td>"]
            if op:
                cells.append(f"<td><span style='background:{hx(led_preview(m.split(op[v])))}'></span>{op[v]:06X}</td>")
            cells.append(f"<td><span style='background:{hx(led_preview(p))}'></span>{m.join(*p):06X}</td>")
            if ol:
                cells.append(f"<td><span style='background:{hx(m.of565(ol[v]))}'></span>{ol[v]:04X}</td>")
            cells.append(f"<td><span style='background:{hx(m.of565(c))}'></span>{c:04X}</td>")
            trs.append("<tr>" + "".join(cells) + "</tr>")
        head = ("<th>vel</th><th>Akai colour</th>" + ("<th>pad old (LED model)</th>" if op else "") +
                "<th>pad new (LED model)</th>" + ("<th>LCD old</th>" if ol else "") + "<th>LCD new</th>")
        Path(a.html).write_text(
            "<!doctype html><meta charset=utf-8><title>APC40 colours</title><style>body{background:#111;"
            "color:#ddd;font:12px monospace}span{display:inline-block;width:40px;height:18px;margin-right:6px;"
            "vertical-align:middle}td{padding:2px 8px}</style><table><tr>" + head + "</tr>" + "".join(trs) +
            "</table>")
    if not (a.pad_h or a.lcd_h or a.gamma_h or a.report or a.html):
        print("vel  source  pad      lcd")
        for e, p, c in zip(src, pad, lcd):
            print(f"{e['v']:3d}  {e['apc']:06X}  {m.join(*p):06X}   {c:04X}")


if __name__ == "__main__":
    main()
