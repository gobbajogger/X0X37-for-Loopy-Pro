PROFILE='smc-vendor-central-dev'
ELF_SHA='32270ce1ee210959e8376205916742f00d54b07815b926f1c44ccc17123c9501'
RESULT_SHA='b1bb745f4505016f87827e9570583405a67f4271b2eb113b9e45df5bfa7b16df'
REGION_SHA=('f932189d1ef6d61b60693347b5fb54d7a0dc7001c2c83e573d98836139b64414',
            '3c3fa1f88b5a080788fce673738c9110bd9c41a78170ca1e6d1d078f6ad63b10',
            '0905950ad661147aa5de2cc1a16ae39f252814af8a48a7065c8d3915f8e5f0ed')

def module(path,name):
    spec=importlib.util.spec_from_file_location(name,path)
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m

def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def require(ok,message):
    if not ok:raise ValueError(message)
def state(repo):
    require(not subprocess.check_output(['git','-C',str(repo),'status','--porcelain','--untracked-files=no'],text=True),'source must be committed and clean')
    return subprocess.check_output(['git','-C',str(repo),'rev-parse','HEAD'],text=True).strip()

def retained_vendor(repo,directory):
    require(sha(directory/'result.json')==RESULT_SHA,'unreviewed retained vendor build record')
    require(sha(directory/'resolved-NOT-FIRMWARE.elf')==ELF_SHA,'retained vendor ELF changed')
    result=json.loads((directory/'result.json').read_text())
    require(result['resolved'] and not result['unresolved'] and result['link_exit']==0,'vendor link unresolved')
    # config/log_tags are deliberately generated by the pinned reference recipe.
    # All runtime sources and shared ABI headers must still match the reviewed ELF.
    for name,digest in result['source_hashes'].items():
        if name in ('src/config.c','src/log_tags.c'):continue
        p=repo/'ble/ctl'/name
        if not p.exists():p=repo/'firmware/hal'/Path(name).name
        require(sha(p)==digest,'retained controller source changed: '+name)
    return result

def build(repo,out,vendor):
    repo=repo.resolve();out=out.resolve();vendor=vendor.resolve()
    commit=state(repo)
    require(not out.exists() and not out.is_relative_to(repo),'output must be new and outside source')
    retained=retained_vendor(repo,vendor)
    combined=module(repo/'tools/studies/smc_bundle_loader/build_combined.py','combined')
    appseal=module(repo/'tools/studies/smc_app_data/seal_fixture.py','appseal')
    segseal=module(repo/'tools/studies/smc_reference/seal_segments.py','segseal')
    out.mkdir(parents=True);app=out/'app';loader=out/'loader-source'
    studies=repo/'tools/studies';target=app/'build/smk37-elite'
    combined.export(repo,combined.BASE,app)
    for script in ('prepare.py','prepare_admission.py','prepare_bridge.py'):
        combined.run(sys.executable,studies/'smc_app_data'/script,app)
    # This named route, not STUDY_ONLY, selects installable DEV semantics. Raw
    # build.py still cannot package; only the separately checked constructor can.
    p=app/'tools/build.py';text=p.read_text()
    old='"-DX0X_SMC_VENDOR_STUDY_ONLY=1"'
    require(text.count(old)==1,'expected exactly one study selector')
    text=text.replace(old,'"-DX0X_SMC_VENDOR_DEV_PACKAGE=1", "-DX0X_SMC_VENDOR_MODEL_ELITE=1"')
    old='    APP_CODE_MAX = fm1pkg_make.APP_CODE_MAX'
    require(text.count(old)==1,'unexpected app limit assignment')
    text=text.replace(old,'    APP_CODE_MAX = 524000  # fixed ABI4 primary boundary, physical0x84000')
    p.write_text(text)
    combined.build(app,out/'app-first.log')
    original=(target/'x0x.bin').read_bytes()
    sealed,ui,appmeta=appseal.seal((target/'x0x.elf').read_bytes(),original)
    components=out/'components';components.mkdir()
    (components/'app.bin').write_bytes(sealed);(components/'ui.bin').write_bytes(ui)
    combined.export(repo,combined.LOADER_BASE,loader)
    combined.run(sys.executable,studies/'smc_bundle_loader/prepare.py',loader,target/'x0x.elf',components/'app.bin')
    for name in ('bp_manifest.h','bp_pin.h','bundle_probe.h','record_owner.h','rollback_pins.h','crt0_ldr.S','ldr_core.c','loader.c'):
        shutil.copyfile(loader/'firmware/loader'/name,app/'firmware/loader'/name)
    shutil.copyfile(loader/'firmware/hal/bp_loader_quiesce.h',app/'firmware/hal/bp_loader_quiesce.h')
    combined.build(app,out/'build.log')
    require((target/'x0x.bin').read_bytes()==original,'paired loader changed pinned app')
    shutil.copyfile(target/'loader/ota.bin',components/'ota.bin')
    images,vmeta=segseal.extract((vendor/'resolved-NOT-FIRMWARE.elf').read_bytes(),'SMK-37 Elite')
    require(len(images)==3 and len(segseal.RANGES)==3,'exactly three controller regions required')
    for i,(image,(off,capacity)) in enumerate(zip(images,segseal.RANGES)):
        region=bytes(image)+b'\xff'*(capacity-len(image))
        require(hashlib.sha256(region).hexdigest()==REGION_SHA[i],'materialized controller differs from reviewed retained image')
        if i:segseal.record_slots(region,off)
        (components/f'vendor-{i}.bin').write_bytes(region)
    pin=(app/'firmware/loader/bp_pin.h').read_text()
    for name,value in {'BP_APPDESC_OFF':appmeta['descriptor_flash_offset'],'BP_APP_SIZE':len(sealed),
                       'BP_APP_CRC':zlib.crc32(sealed)}.items():
        match=re.search(r'#define '+name+r' (0x[0-9a-fA-F]+|[0-9]+)u',pin)
        require(match is not None and int(match[1],0)==value,'compiled loader pin mismatch: '+name)
    require(state(repo)==commit,'source changed while building')
    result={'schema':1,'profile':PROFILE,'model':'elite','config':'dev','source_commit':commit,
            'hardware_tested':False,'package_admitted':False,'app_limit':524000,
            'app_free':524000-len(sealed),'controller_reused':True,'controller_elf_sha256':ELF_SHA,
            'controller_record_sha256':RESULT_SHA,'controller_layout':retained['placed_flash'],
            'controller_ram':{'low':retained['ram_extent_bytes'],'high':retained['high_cpu_bytes']},
            'app':appmeta,'vendor':vmeta,
            'loader_binding':{'ota_sha256':sha(components/'ota.bin'),'app_sha256':sha(components/'app.bin'),
                'app_size':len(sealed),'app_crc32':zlib.crc32(sealed),'descriptor_off':appmeta['descriptor_flash_offset']},
            'artifacts':{p.name:{'size':p.stat().st_size,'sha256':sha(p)} for p in sorted(components.iterdir())},
            'private_debug':{name:sha(target/name) for name in ('x0x.elf','x0x.map','loader/loader.elf') if (target/name).exists()}}
    (out/'components.json').write_text(json.dumps(result,indent=2)+'\n')
    print(f"SMC central DEV components: app {len(sealed)} B, {524000-len(sealed)} B free; retained resolved vendor; no package admission")
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--repo',type=Path,required=True);p.add_argument('--out',type=Path,required=True)
    p.add_argument('--vendor-dir',type=Path,required=True)
    p.add_argument('--profile',choices=(PROFILE,),required=True)
    p.add_argument('--model',choices=('elite',),required=True);p.add_argument('--config',choices=('dev',),required=True)
    a=p.parse_args()
    # Never inherit ambient feature/diagnostic selectors into a validated profile.
    from dev_validate import development_env
    env=development_env(os.environ,'elite')
    for key in list(env):
        if key.startswith('X0X_SMC_'):env.pop(key)
    os.environ.clear();os.environ.update(env)
    build(a.repo,a.out,a.vendor_dir)

if __name__=='__main__':main()
