"""Generate gen/rf_tables.c from the pinned SDK file apps/common/net/wifi_conf.c.
The output is SDK data (Apache-2.0) and carries that licence. Nothing is typed by hand:
the script copies the active '#else' branch (the WiFi RX constants and wl_rfd_ram_lut)."""
import hashlib, os, sys
SRC = os.path.join(os.path.dirname(__file__), 'lib', 'wifi_conf.c')
SHA = '697c798b6a9c992c75ee3959aa58d121d4eb3015474250ad8f9156a9a22fe6bb'
data = open(SRC, 'rb').read()
if hashlib.sha256(data).hexdigest() != SHA:
    sys.exit('wifi_conf.c SHA-256 mismatch')
lines = data.decode('utf-8', 'replace').splitlines()
# Find '#if 0  //WIFI RX' and take the lines between its '#else' and '#endif'.
i = next(n for n, l in enumerate(lines) if l.startswith('#if 0') and 'WIFI RX' in l)
e = next(n for n in range(i + 1, len(lines)) if lines[n].startswith('#else'))
z = next(n for n in range(e + 1, len(lines)) if lines[n].startswith('#endif'))
body = [l for l in lines[e + 1:z]]
os.makedirs(os.path.join(os.path.dirname(__file__), 'gen'), exist_ok=True)
with open(os.path.join(os.path.dirname(__file__), 'gen', 'rf_tables.c'), 'w') as f:
    f.write('// SPDX-License-Identifier: Apache-2.0\n')
    f.write('/* GENERATED by gen_rf_tables.py from JieLi fw-AC79_AIoT_SDK d179b44\n'
            ' * apps/common/net/wifi_conf.c lines %d-%d (Apache-2.0, (c) Zhuhai Jieli). Do not edit. */\n' % (e + 2, z))
    f.write('typedef unsigned int u32;\n')
    f.write('\n'.join(body) + '\n')
print('rf_tables.c: %d lines' % len(body))
